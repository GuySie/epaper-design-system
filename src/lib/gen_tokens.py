#!/usr/bin/env python3
"""Generate the per-tier tokens (EP_TIER in lib/ep_tokens.jinja): nothing in it is written by hand.

  gen_tokens.py KEYS      derive every tier from its panel facts (lib/derive_tokens.py KNOWN), build a package of the
                          layouts KEYS (comma-separated, as release.sh passes them), fit the measured tokens on it
                          (lib/layout_fit.py) and write EP_TIER between its markers in lib/ep_tokens.jinja
Floors, derived tokens and steps up come from derive_tokens.derive; the line strokes follow line.base; the pitch is the
panel's (mm per pixel, to 0.001). The measured tokens are per layout (EP_LAYOUT); a layout
whose fit inputs are unchanged keeps its tokens (lib/ep_tokens.fit.json, layout_hash; EP_REFIT=1 fits every layout).
"""
import pathlib, shutil, subprocess, sys, tempfile
LIB = pathlib.Path(__file__).resolve().parent
SRC = LIB.parent
sys.path.insert(0, str(LIB))
from derive_tokens import KNOWN, derive, font_files, XS, S, STROKES, STROKE_MIN_MM, TIGHT_MM, UNIT_GAP_NONE, COLOR, NATIVE, ICON_LADDER, TIME_TICKS, HERO_GAP_DIV, CHART_TOP   # noqa: E402
from hero_metrics import pairs, HERO_LADDER      # noqa: E402
import layout_fit                                # noqa: E402

TOKENS = LIB / 'ep_tokens.jinja'
FITS = LIB / 'ep_tokens.fit.json'      # layout -> the hash of what its measured tokens were fitted from
BEGIN, END = "{#- generated by lib/gen_tokens.py: don't edit by hand -#}", '{#- end of generated EP_TIER -#}'


def entry(key):
    """the tier's tokens from its panel facts (the measured ones are per layout: layout_entry)"""
    d, _ = derive(*KNOWN[key])
    b = d['line']['base']
    t = {k: v[:2] for k, v in d['type'].items() if k not in ('primary', 'heroAlone floor')}
    return {
        'width': d['width'], 'height': d['height'], 'pitch': d['pitch'],
        'space': {k: d['space'][k] for k in ('pad', 'm', 'l', 'titleRow', 'row', 'rowDense', 'detailRow', 'footer', 'axis')},
        'type': {**{k: t[k] for k in ('title', 'stamp', 'label', 'fieldLabel', 'data')}, 'primary': d['type']['primary'],
                 'unit': t['unit'], 'secondary': t['secondary']},
        'icon': {'min': d['icon']['min'], 'inline': d['icon']['inline'], 'markerDisc': d['icon']['markerDisc']},
        'line': {'base': b, 'tick': STROKES['tick'] * b, 'dash': [m * b for m in STROKES['dash']], 'dot': [m * b for m in STROKES['dot']],
                 'forecastDash': [m * b for m in STROKES['forecastDash']], 'series': d['line']['series'],
                 'heavy': STROKES['heavy'] * b, 'barGap': STROKES['barGap'] * b},
    }, d['type']['heroAlone floor']


def lit(v):
    if v is None:
        return 'none'
    if isinstance(v, str):
        return f"'{v}'"
    if isinstance(v, list):
        return '[' + ', '.join(lit(x) for x in v) + ']'
    if isinstance(v, dict):
        return '{' + ', '.join(f"'{k}': {lit(x)}" for k, x in v.items()) + '}'
    return str(v)


def layout_entry():
    """a layout's measured tokens (*Token register*, *Measured*): its hero and strip icons, empty until fitted"""
    return {'type': {'heroAlone': None, 'heroShared': None},
            'icon': {'heroShared': None, 'heroAloneSteps': None, 'stripHour': None, 'stripDay': None}}


def block(tiers, lays):
    out = [BEGIN, '{%- set EP_TIER = {']
    for n, (key, e) in enumerate(tiers.items()):
        out.append(f"  '{key}': {{")
        out.append(f"    'width': {e['width']}, 'height': {e['height']}, 'pitch': {e['pitch']},")
        out.append(',\n'.join(f"    '{s}': {lit(e[s])}" for s in ('space', 'type', 'icon', 'line')))
        out.append('  }' + (',' if n < len(tiers) - 1 else ''))
    out += ['} -%}', "{#- the measured tokens, per layout (by its public name): laid over its tier's tokens in ep_draw -#}"]
    out += ['{%- set EP_LAYOUT = {']
    for n, (name, e) in enumerate(lays.items()):
        out.append(f"  '{name}': {{")
        out.append(',\n'.join(f"    '{s}': {lit(e[s])}" for s in ('type', 'icon')))
        out.append('  }' + (',' if n < len(lays) - 1 else ''))
    out += ['} -%}', END]
    return '\n'.join(out)


SBEGIN, SEND = "{#- generated by lib/gen_tokens.py from lib/derive_tokens.py: don't edit by hand -#}", '{#- end of generated EP_FONT, EP_SPACE, EP_STROKE, EP_COLOR, EP_ICON, EP_CHART -#}'


def unit_gap():
    """space.unitGap: the width of a space in each native size's Regular cut (measured)"""
    from PIL import ImageFont
    return {str(n): int(ImageFont.truetype(str(SRC / 'fonts' / f'TRMNL{n}-Regular.ttf'), n).getlength(' ')) for n in NATIVE}


def style_block():
    """the tokens that are the same on every tier: font files, text-bound space, the stroke floor, colour roles"""
    def d(name, v):
        return '{%- set ' + name + ' = ' + lit(v) + ' -%}'
    space = {'xs': {str(k): v for k, v in XS.items()}, 's': {str(k): v for k, v in S.items()}, 'unitGap': unit_gap(),
             'unitGapNone': UNIT_GAP_NONE, 'tightMm': TIGHT_MM, 'heroGapDiv': HERO_GAP_DIV}
    return '\n'.join([SBEGIN, d('EP_FONT', font_files()), d('EP_SPACE', space), d('EP_STROKE', {'strokeMinMm': STROKE_MIN_MM}),
                      d('EP_COLOR', COLOR), d('EP_ICON', {'ladder': ICON_LADDER}), d('EP_CHART', {'timeTicks': TIME_TICKS, 'top': CHART_TOP}), SEND])


def write_style():
    src = TOKENS.read_text()
    i, j = src.index(SBEGIN), src.index(SEND) + len(SEND)
    TOKENS.write_text(src[:i] + style_block() + src[j:])


def write(tiers, lays, fits=None):
    """the tokens into lib/ep_tokens.jinja; fits: what each layout's fit was made from (layout_hash), kept beside the
    tokens in FITS and not in the template, so the shipped templates only change when a token does"""
    import json
    src = TOKENS.read_text()
    i, j = src.index(BEGIN), src.index(END) + len(END)
    TOKENS.write_text(src[:i] + block(tiers, lays) + src[j:])
    FITS.write_text(json.dumps(fits or {}, indent=1, sort_keys=True) + '\n')


def build(out, keys):
    import build as pipeline          # the one build (lib/build.py); the fit needs no set id
    pipeline.build(out, keys, set_id=False)


# sources that never reach a render or the fit: the document's tables, the reference tools, the case lists (a layout's
# own cases are hashed by layout_hash) and the release script
NOT_FIT = {'lib/coverage.py', 'lib/doc_values.py', 'lib/tier_tables.py', 'lib/baseline.py', 'lib/golden.py', 'lib/preview.py', 'lib/impact.py', 'lib/rules.py', 'lib/rules.lock.json',
           'lib/pixcmp_cases.py', 'release.sh', 'lib/ep_tokens.fit.json'}


def _digest(files, *more):
    import hashlib
    h = hashlib.sha256()
    for f in sorted(set(files)):
        b = f.read_bytes()
        if f == TOKENS:                     # the generated block is the result, not an input
            t = b.decode('utf-8'); i, j = t.index(BEGIN), t.index(END) + len(END); b = (t[:i] + t[j:]).encode('utf-8')
        h.update(f.relative_to(SRC).as_posix().encode() + b'\0' + b + b'\0')
    h.update('|'.join(str(m) for m in more).encode())
    return h.hexdigest()


def common_hash():
    """what every layout's fit depends on: every source in src/ except the references, the build output, caches, the
    tools in NOT_FIT and what belongs to single layouts (specs, scenarios, page definitions: layout_hash), and the
    versions of what renders (Python, Pillow with Raqm, the renderer, Jinja, PyYAML, numpy)"""
    import platform
    from importlib.metadata import version
    from PIL import features
    files = []
    for f in SRC.rglob('*'):
        rel = f.relative_to(SRC).as_posix()
        if not f.is_file() or rel.split('/')[0] in ('baseline', 'build', 'specs', 'scen') or '__pycache__' in rel or f.suffix == '.pyc' or any(s.startswith('.') for s in rel.split('/')):
            continue
        if rel in NOT_FIT or (rel.startswith('pages/') and rel != 'pages/_shared.yaml'):
            continue
        files.append(f)
    return _digest(files, platform.python_version(), features.check('raqm'),
                   *(version(p) for p in ('pillow', 'odl-renderer', 'jinja2', 'pyyaml', 'numpy')))


def _with_loaded(folder, stems):
    """the files of folder named by stems and every file of the folder they name in turn (a scenario or a spec that
    loads another), plus the folder's shared pieces (_*.py)"""
    import re
    files = {p.stem: p for p in folder.glob('*.py')}
    todo, seen = list(stems) + [s for s in files if s.startswith('_')], set()
    while todo:
        s = todo.pop()
        if s in seen or s not in files:
            continue
        seen.add(s)
        todo += [w for w in set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', files[s].read_text(encoding='utf-8'))) if w in files and w not in seen]
    return [files[s] for s in seen]


def layout_hash(l, common):
    """what one layout's fit depends on: the common sources, its drawing, its page definition, its check cases and
    fitter entries, and the scenarios they name"""
    import check
    key = l['key']
    cases = sorted(c for c in check.CASES + check.EXTRA_CASES if c[1] == key)
    fit = (layout_fit.FIT.get(key), key in layout_fit.STRIP, layout_fit.GLANCE.get(key))
    scens = {c[0] for c in cases} | {s for s, _ in fit[0] or []} | set(fit[2] or [])
    missing = sorted(s for s in scens if not (SRC / 'scen' / f'{s}.py').exists())
    if missing:
        sys.exit(f'{key}: no scenario file for {", ".join(missing)}')
    files = _with_loaded(SRC / 'specs', [l['spec']]) + _with_loaded(SRC / 'scen', scens) + [SRC / 'pages' / f"{l['page']}.yaml"]
    return _digest(files, common, l['name'], l['tier'], cases, fit)


def fitted():
    """the layouts' tokens and fit hashes as lib/ep_tokens.jinja has them now ({} when it can't be read)"""
    import json, jinja2
    try:
        return jinja2.Environment().from_string(TOKENS.read_text()).module.EP_LAYOUT, json.loads(FITS.read_text())
    except Exception:
        return {}, {}


def main(keys):
    import os
    write_style()                           # from derive_tokens (an input of the fit), so before the hashes
    P = pairs()
    from layouts import layouts
    tiers, floors, lays = {}, {}, {}
    for key in KNOWN:
        tiers[key], floors[key] = entry(key)
    L = [l for l in layouts() if l['spec'] in keys.split(',')]
    common = common_hash()
    want = {l['name']: layout_hash(l, common) for l in L}
    old, had = fitted()
    keep = set() if os.environ.get('EP_REFIT') else {n for n, h in want.items() if had.get(n) == h and n in old}
    for l in L:
        e = lays[l['name']] = layout_entry()
        if l['name'] in keep:               # fitted before from the same inputs: the same answer
            for sect in e:
                e[sect] = {k: old[l['name']][sect][k] for k in e[sect]}
            continue
        # starting values for the fit: the smallest rung where the layout has a hero, the strip icons at their smallest
        if l['key'] in layout_fit.FIT:
            e['type']['heroShared'], e['icon']['heroShared'] = HERO_LADDER[0], P[HERO_LADDER[0]][1]
        if l['key'] in layout_fit.GLANCE:
            e['type']['heroAlone'], e['icon']['heroAloneSteps'] = floors[l['tier']], P[floors[l['tier']]][2]
        if l['key'] in layout_fit.STRIP:
            e['icon']['stripDay'] = tiers[l['tier']]['icon']['min']
    todo = [l for l in L if l['name'] not in keep]
    if not todo:
        write(tiers, lays, want)
        print(f'{TOKENS.name}: no layout\'s fit inputs changed, tokens kept (EP_REFIT=1 fits anyway)')
        return
    before, fits_before = TOKENS.read_text(), (FITS.read_text() if FITS.exists() else '{}\n')
    import signal                           # a release stopped mid-fit restores the tokens like any failure (below)
    signal.signal(signal.SIGTERM, lambda *_: sys.exit('stopped'))
    write(tiers, lays)
    work = pathlib.Path(tempfile.mkdtemp(prefix='tokens_'))
    try:
        build(str(work / 'pkg'), keys)
        f = layout_fit.Fitter(work / 'pkg')
        # each layout on its own, in the Hero dashboard's what-gives-way order: its hero, then its strip icons
        for l in todo:
            e, key = lays[l['name']], l['key']
            if key in layout_fit.FIT:
                h = f.hero_shared(l['name'], key)
                e['type']['heroShared'], e['icon']['heroShared'] = h, P[h][1]
            if key in layout_fit.STRIP:
                e['icon']['stripHour'], e['icon']['stripDay'] = f.strips(l['name'], key, tiers[l['tier']]['icon']['min'])
            if key in layout_fit.GLANCE:
                h = f.hero_alone(l['name'], key, floors[l['tier']])
                e['type']['heroAlone'], e['icon']['heroAloneSteps'] = h, P[h][2]
        print('\n'.join(f.log))
    except BaseException:
        TOKENS.write_text(before); FITS.write_text(fits_before)     # a fit that fails leaves the tokens as they were
        raise
    finally:
        shutil.rmtree(work, ignore_errors=True)
    write(tiers, lays, want)                # each layout's hash goes with its result: the next release fits only what changed
    print(f'{TOKENS.name}: EP_TIER for {len(tiers)} tiers, EP_LAYOUT for {len(lays)} layouts ({len(todo)} fitted, {len(keep)} kept)')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
